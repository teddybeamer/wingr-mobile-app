function completion(
  content: unknown = JSON.stringify(providerResult),
  finish_reason = "stop",
) {
  return Response.json({ choices: [{ finish_reason, message: { content } }] });
}
test("one multimodal request uses Gemini with low reasoning by default, standard Vertex only and mandatory privacy", async () => {
  let calls = 0;
  const value = await analyzeWithGemini(
    {
      ...input,
      selectedTone: "casualSmallTalk",
      extraContext: "Jeg vil holde det afslappet.",
      previousWingrSuggestions: [
        "Det lyder hyggeligt — hvordan går din søndag?",
        "Så må du fortælle mere om det på en kaffe.",
      ],
    },
    "secret",
    {
      fetchImpl: async (url, init) => {
        calls++;
        assert.equal(url, "https://openrouter.ai/api/v1/chat/completions");
        assert.equal(
          new Headers(init?.headers).get("authorization"),
          "Bearer secret",
        );
        const body = JSON.parse(String(init?.body));
        assert.equal(body.model, GEMINI_MODEL);
        assert.equal(body.model, "google/gemini-3.8-flash");
        assert.deepEqual(body.reasoning, { effort: "low" });
        assert.equal(body.service_tier, "default");
        assert.equal(body.max_tokens, 5000);
        assert.equal(body.max_completion_tokens, undefined);
        assert.deepEqual(body.provider, {
          only: ["google-vertex/global"],
          zdr: true,
          data_collection: "deny",
          allow_fallbacks: false,
          require_parameters: true,
        });
        assert.equal(body.response_format.type, "json_schema");
        assert.equal(body.response_format.json_schema.strict, true);
        assert.deepEqual(body.messages[1].content[1], {
          type: "image_url",
          image_url: { url: input.screenshot },
        });
        assert.deepEqual(JSON.parse(body.messages[1].content[0].text), {
          selectedTone: "casualSmallTalk",
          extraContext: "Jeg vil holde det afslappet.",
          previousWingrSuggestions: [
            "Det lyder hyggeligt — hvordan går din søndag?",
            "Så må du fortælle mere om det på en kaffe.",
          ],
        });
        assert.equal(body.models, undefined);
        assert.equal(body.plugins, undefined);
        return completion();
      },
    },
  );
  assert.equal(calls, 1);
  assert.deepEqual(value, providerResult);
});
test("reports a compact-contract provider duration without request content", async () => {
  const measurements: unknown[] = [];
  await analyzeWithGemini(input, "secret", {
    fetchImpl: async () => completion(),
    onProviderLatency: (measurement) => measurements.push(measurement),
  });
  assert.equal(measurements.length, 1);
  assert.deepEqual(Object.keys(measurements[0] as object).sort(), [
    "durationMs",
    "model",
    "outcome",
    "outputContract",
    "provider",
  ]);
  assert.deepEqual(measurements[0], {
    durationMs: (measurements[0] as { durationMs: number }).durationMs,
    model: "google/gemini-3.8-flash",
    outcome: "success",
    outputContract: AI_OUTPUT_CONTRACT,
    provider: "google-vertex/global",
  });
  assert.equal(
    typeof (measurements[0] as { durationMs: unknown }).durationMs,
    "number",
  );
  assert.ok((measurements[0] as { durationMs: number }).durationMs >= 0);
  const serialized = JSON.stringify(measurements);
  for (const privateValue of ["secret", input.screenshot])
    assert.ok(!serialized.includes(privateValue));
});
