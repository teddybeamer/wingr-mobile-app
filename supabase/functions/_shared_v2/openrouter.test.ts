test("malformed, refused, truncated and schema-invalid completions terminate without retries", async () => {
  for (const response of [
    completion("not JSON"),
    completion("```json {} ```"),
    completion(JSON.stringify(providerResult), "length"),
    completion(
      JSON.stringify({
        ...providerResult,
        messages: [{ speaker: "THEM", text: "Hi" }],
      }),
    ),
    completion(null),
    Response.json({ choices: [] }),
    new Response("not JSON"),
  ]) {
    let calls = 0;
    await assert.rejects(
      analyzeWithGemini(input, "key", {
        fetchImpl: async () => {
          calls++;
          return response;
        },
      }),
      (error: unknown) =>
        error instanceof ConversationError && error.kind === "invalid_output",
    );
    assert.equal(calls, 1);
  }
});
test("provider HTTP and network errors are safe terminal errors and never retry", async () => {
  for (const mode of ["http", "network", "envelope"]) {
    let calls = 0;
    await assert.rejects(
      analyzeWithGemini(input, "key", {
        fetchImpl: async () => {
          calls++;
          if (mode === "network") throw new Error("PRIVATE CONVERSATION");
          return mode === "http"
            ? new Response("PRIVATE CONVERSATION", { status: 503 })
            : Response.json({ error: { message: "PRIVATE CONVERSATION" } });
        },
      }),
      (error: unknown) =>
        error instanceof ConversationError &&
        error.kind === "provider" &&
        !error.message.includes("PRIVATE"),
    );
    assert.equal(calls, 1);
  }
});
test("timeout covers fetch and stalled response body and aborts with one attempt", async () => {
  for (const phase of ["fetch", "body"]) {
    let calls = 0;
    await assert.rejects(
      analyzeWithGemini(input, "key", {
        timeoutMs: 5,
        fetchImpl: async (_url, init) => {
          calls++;
          const stalled = () =>
            new Promise<never>((_resolve, reject) =>
              init?.signal?.addEventListener(
                "abort",
                () => reject(new DOMException("Aborted", "AbortError")),
                { once: true },
              ),
            );
          if (phase === "fetch") return stalled();
          const response = new Response();
          response.json = stalled;
          return response;
        },
      }),
      (error: unknown) =>
        error instanceof ConversationError && error.kind === "timeout",
    );
    assert.equal(calls, 1);
  }
});

test("provider status survives both HTTP failures and HTTP-200 error envelopes", async () => {
  for (const status of [400, 401, 402, 403, 404, 429, 503]) {
    for (const envelope of [false, true]) {
      await assert.rejects(
        analyzeWithGemini(input, "key", {
          fetchImpl: async () =>
            envelope
              ? Response.json({
                  error: {
                    code: status,
                    message: "PRIVATE CHAT",
                    metadata: { raw: "PRIVATE CHAT" },
                  },
                })
              : new Response("PRIVATE CHAT", { status }),
        }),
        (failure: unknown) => {
          assert.ok(failure instanceof ConversationError);
          assert.equal(failure.kind, "provider");
          assert.equal(failure.providerStatus, status);
          assert.ok(!failure.message.includes("PRIVATE"));
          return true;
        },
      );
    }
  }
});

test("configuration errors expose fixed explanations without leaking upstream text", async () => {
  const cases = [
    ["google/example is not a valid model ID", "model_unavailable"],
    ["The user field is required", "user_required"],
    ["Invalid response schema", "schema_rejected"],
    ["Invalid image data", "image_rejected"],
    ["No endpoints found that match your data policy", "routing_unavailable"],
  ];
  for (const [message, reason] of cases) {
    await assert.rejects(
      analyzeWithGemini(input, "key", {
        fetchImpl: async () =>
          Response.json(
            { error: { message: `${message}. PRIVATE CHAT` } },
            { status: 400 },
          ),
      }),
      (failure: unknown) => {
        assert.ok(failure instanceof ConversationError);
        assert.equal(failure.providerReason, reason);
        assert.ok(!failure.message.includes("PRIVATE"));
        return true;
      },
    );
  }
});

test("reasoning effort defaults to low and only the exact value medium switches back", () => {
  assert.equal(parseReasoningEffort(undefined), "low");
  assert.equal(parseReasoningEffort(null), "low");
  assert.equal(parseReasoningEffort(""), "low");
  assert.equal(parseReasoningEffort("high"), "low");
  assert.equal(parseReasoningEffort("MEDIUM"), "low");
  assert.equal(parseReasoningEffort("minimal"), "low");
  assert.equal(parseReasoningEffort(" medium "), "medium");
  assert.equal(buildOpenRouterRequest(input).reasoning.effort, "low");
  assert.equal(
    buildOpenRouterRequest(input, "medium").reasoning.effort,
    "medium",
  );
});

test("the effort setting changes nothing but the effort: routing, model and contract stay pinned", () => {
  const medium = buildOpenRouterRequest(input, "medium");
  const low = buildOpenRouterRequest(input);
  assert.equal(medium.reasoning.effort, "medium");
  assert.equal(low.reasoning.effort, "low");
  assert.deepEqual({ ...low, reasoning: medium.reasoning }, medium);
  assert.deepEqual(low.provider, {
    only: ["google-vertex/global"],
    zdr: true,
    data_collection: "deny",
    allow_fallbacks: false,
    require_parameters: true,
  });
  assert.equal(low.model, GEMINI_MODEL);
});

test("Gemini is the default model; AI_MODEL only selects a known preset and anything else falls back", () => {
  assert.equal(DEFAULT_MODEL, "google/gemini-3.8-flash");
  assert.equal(DEFAULT_MODEL, GEMINI_MODEL);
  for (const value of [
    undefined,
    null,
    "",
    "   ",
    "google/gemini-3.8-flash",
    "deepseek/deepseek-v4.1-flash",
    "~deepseek/deepseek-flash-latest",
    "DEEPSEEK/DEEPSEEK-V4.1-FLASH-1017",
    "openai/gpt-5",
    "__proto__",
    "toString",
    "constructor",
  ])
    assert.equal(parseModel(value), GEMINI_MODEL, String(value));
  assert.equal(parseModel("deepseek/deepseek-v4.1-flash-1017"), DEEPSEEK_MODEL);
  assert.equal(
    parseModel(" deepseek/deepseek-v4.1-flash-1017 "),
    DEEPSEEK_MODEL,
  );
  assert.equal(buildOpenRouterRequest(input).model, GEMINI_MODEL);
  assert.equal(providerForModel(GEMINI_MODEL), "google-vertex/global");
  assert.equal(providerForModel(DEEPSEEK_MODEL), "inference-net/fp8");
});

test("the DeepSeek preset pins inference.net with mandatory privacy and always sends an explicit reasoning effort", () => {
  const body = buildOpenRouterRequest(input, "low", DEEPSEEK_MODEL);
  assert.equal(body.model, "deepseek/deepseek-v4.1-flash-1017");
  assert.deepEqual(body.provider, {
    only: ["inference-net/fp8"],
    zdr: true,
    data_collection: "deny",
    allow_fallbacks: false,
    require_parameters: true,
  });
  // DeepSeek thinks at "high" when no effort is sent, and rejects "medium".
  assert.deepEqual(body.reasoning, { effort: "low" });
  assert.deepEqual(
    buildOpenRouterRequest(input, "medium", DEEPSEEK_MODEL).reasoning,
    {
      effort: "high",
    },
  );
  for (const effort of ["low", "medium"] as const) {
    const reasoning = buildOpenRouterRequest(
      input,
      effort,
      DEEPSEEK_MODEL,
    ).reasoning;
    assert.ok(["low", "high"].includes(reasoning.effort));
  }
  assert.ok(!("models" in body));
  assert.ok(!("plugins" in body));
});

test("switching the model changes only the model, provider and reasoning mapping, never the prompt, schema or limits", () => {
  const gemini = buildOpenRouterRequest(input, "low", GEMINI_MODEL);
  const deepseek = buildOpenRouterRequest(input, "low", DEEPSEEK_MODEL);
  assert.deepEqual(gemini.reasoning, { effort: "low" });
  assert.deepEqual(gemini.provider.only, ["google-vertex/global"]);
  assert.deepEqual(deepseek.messages, gemini.messages);
  assert.deepEqual(deepseek.response_format, gemini.response_format);
  assert.equal(deepseek.response_format.json_schema.strict, true);
  assert.equal(deepseek.max_tokens, gemini.max_tokens);
  assert.equal(deepseek.service_tier, gemini.service_tier);
  assert.deepEqual(
    { ...deepseek.provider, only: undefined },
    { ...gemini.provider, only: undefined },
  );
});

